def diag_corrected():
    """distill_diag.txt -> {(setting, seed): (exact, R2 against the truth, expression)} of the diagonal-corrected
    coupling g'(x_i, x_j) = g(x_i, x_j) - g(x_i, x_i), the form the paper reports."""
    out, L = {}, lines("distill_diag.txt")
    for k, l in enumerate(L):
        sn = split_name(l, EQSET)
        if not sn:
            continue
        m = re.match(r"\s+(\d)\s+g\s", sn[1])
        if not m:
            continue
        g2 = re.match(r"\s+g'\s+([\d.]+)\s+([\d.]+)\s+[\d.]+\s+\S+\s+(yes|no)", L[k + 1]); assert g2, L[k + 1]
        ex = re.match(r"\s+g' = (.*?)(\s+\(g\(x_i, x_i\) = 0 identically: g' = g\))?$", L[k + 3]); assert ex, L[k + 3]
        out[(sn[0], m.group(1))] = (g2.group(3), "%.3f" % float(g2.group(2)), ex.group(1), ex.group(2) is not None)
    assert len(out) == 18
    return out


def equations_nonexact():
    """skeleton_match_full.txt -> eq_nonexact.tex: the equations that fail the exactness test. Coupling rows use the
    diagonal-corrected form of distill_diag.txt: where the correction leaves g unchanged the row is the
    original; counts asserted against the paper (40 of 53 self-fields, 13 of 18 coupling laws). Self-field equations come
    from the per-node distillation and are printed with each constant at its median over the nodes of the class."""
    D = diag_corrected()
    L = lines("skeleton_match_full.txt"); c0 = next(i for i, l in enumerate(L) if l.startswith("coupling laws"))
    selfr, coup = [], []; nself = nexs = ncoup = nexc = 0
    for l in L[:c0]:
        sn = split_name(l, EQSET)
        if not sn:
            continue
        m = re.match(r"\s+(\d)\s+(\S+)\s+(.*?)\s+(d\w+/dt)\s+(yes|no)\s+(yes|no)\s+(-?[\d.]+)\s+(.*)$", sn[1]); s, grp, tr, co, ex, _, r2, eq = m.groups()
        nself += 1; nexs += ex == "yes"
        if ex == "no":
            selfr.append(" & ".join([NAME[sn[0]], s, "%s, %s" % (TRUE_SELF[tr.strip()], COORD[co]), "$%s$" % r2, eq_tex(eq)]) + r"\\")
    for l in L[c0:]:
        sn = split_name(l, EQSET)
        if not sn:
            continue
        m = re.match(r"\s+(\d)\s+(.*?)\s+(yes|no)\s+(yes|no)\s+([\d.]+)\s+([\d.]+)\s+(.*)$", sn[1])
        if not m:
            continue
        s, tr, ex, _, r2, al, eq = m.groups(); ncoup += 1
        ex2, r22, eq2, same = D[(sn[0], s)]
        if same:
            assert ex2 == ex and abs(float(r22) - float(r2)) <= 1.5e-3, (sn[0], s)
        else:
            ex, r2, eq = ex2, r22, eq2
        nexc += ex == "yes"
        if ex == "no":
            coup.append(" & ".join([NAME[sn[0]], s, TRUE_C[tr.strip()], "$%s$" % r2, eq_tex(eq)]) + r"\\")
    assert (nself, nexs, ncoup, nexc) == (53, 40, 18, 13), (nself, nexs, ncoup, nexc)
    assert len(selfr) == 13 and len(coup) == 5
    write("eq_nonexact.tex", tabular(r"l@{\hspace{5pt}}c@{\hspace{5pt}}l@{\hspace{5pt}}r@{\hspace{7pt}}>{\raggedright\arraybackslash}p{4.7cm}",
          r"Setting & Seed & True law & $R^2$ & Distilled equation\\",
          [r"\multicolumn{5}{@{}l}{\emph{Self-fields}}\\"] + selfr + [r"\addlinespace[3pt]", r"\multicolumn{5}{@{}l}{\emph{Coupling laws}}\\"] + coup),
          "skeleton_match_full.txt, distill_diag.txt")



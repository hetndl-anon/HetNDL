def lines(f):
    return open(os.path.join(SRC, f), encoding="utf-8").read().split("\n")


def split_name(line, names):
    """(name, rest) for the longest known row name the line starts with, else None."""
    for n in sorted(names, key=len, reverse=True):
        if line.startswith(n + " "):
            return n, line[len(n):]
    return None


def sci(x):
    m, e = ("%.2e" % float(x)).split("e")
    return r"$%s\times10^{%d}$" % (m, int(e))


def sci1(x):
    m, e = ("%.1e" % x).split("e")
    return r"$%s\times10^{%d}$" % (m, int(e))


def rng(xs, fmt="%.3f"):
    f = fmt if callable(fmt) else (lambda x: fmt % x)
    lo, hi = f(min(xs)), f(max(xs))
    return lo if lo == hi else lo + "--" + hi


def ratio_fmt(x):
    return "%.0f" % x if x >= 10 else "%.1f" % x if x >= 1 else "%.2f" % x if x >= 0.1 else "%.3f" % x


def write(name, body, src):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as f:
        f.write("%% Generated by experiments/analysis/supp_tables.py from %s. Do not edit by hand.\n%s\n" % (src, body))
    print("wrote %s (%d lines)" % (name, body.count("\n") + 1))


def tabular(spec, head, rows):
    return "\\begin{tabular}{@{}%s@{}}\n\\toprule\n%s\n\\midrule\n%s\n\\bottomrule\n\\end{tabular}" % (spec, head, "\n".join(rows))



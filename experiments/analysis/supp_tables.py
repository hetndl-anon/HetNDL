def binary():
    """binary_ours.tex: the 2-means cut on our weights next to the spread of the true weights."""
    L = lines("binary_graph_table.txt"); i0 = next(i for i, l in enumerate(L) if l.startswith("means over the data seeds"))
    means = {}
    for l in L[i0 + 2:]:
        sn = split_name(l, ORDER)
        if not sn:
            break
        m = re.match(r"\s+(ours|NOGI|ARNI full|ARNI greedy|Granger|NRI|AIDD|COSINE|MTGNN|SGODE)\s+(\d+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+(\d+)\s*$", sn[1])
        means[(sn[0], m.group(1))] = m.groups()[1:]
    W = lines("weight_spread.txt"); j0 = next(i for i, l in enumerate(W) if l.startswith("means over the data seeds"))
    spread = {}
    for l in W[j0 + 2:]:
        sn = split_name(l, ORDER)
        if not sn:
            break
        spread[sn[0]] = sn[1].split()
    rows = []
    for n in ORDER:
        _, P, Rc, F1, false = means[(n, "ours")]; cv, mm, rt, ro = spread[n]
        assert abs(float(ro) - float(Rc)) < 2e-3, (n, ro, Rc)          # the two scripts must agree on our recall
        rows.append(" & ".join([NAME[n], P, Rc, false, cv, "%.1f" % float(mm), rt]) + r"\\")
    write("binary_ours.tex", tabular("lcccccc", r" & \multicolumn{3}{c}{Cut on the learned $|W|$} & \multicolumn{3}{c}{True weights}\\" "\n"
          r"\cmidrule(lr){2-4}\cmidrule(l){5-7}" "\n" r"Setting & Precision & Recall & False edges & CV & Max/min & Recall\\", rows),
          "binary_graph_table.txt, weight_spread.txt")


# ------------------------------------------------------------------------------------ per-seed results (S4)
def _per_seed():
    """{setting: [(seed, pick, {method: (auroc, auprc)}), ...]}, {setting: {method: (auroc, auprc)}} (the file's means)."""
    per = {}; means = {}
    for l in lines("baseline_table_per_seed.txt"):
        sn = split_name(l, OLD)
        if not sn:
            continue
        m = re.match(r"\s+(\d)\s+([ns])\s+(.*)$", sn[1]); mu = re.match(r"\s+mean\s+(.*)$", sn[1])
        cells = re.findall(r"([\d.]+) / ([\d.]+)|(—)", (m.group(3) if m else mu.group(1)))
        assert len(cells) == len(FILE_COLS), l
        d = {k: (None if c[2] else (c[0], c[1])) for k, c in zip(FILE_COLS, cells)}
        if m:
            per.setdefault(OLD[sn[0]], []).append((m.group(1), m.group(2), d))
        else:
            means[OLD[sn[0]]] = d
    assert len(per) == 12 and all(len(v) == 3 for v in per.values()) and len(means) == 12
    return per, means


def per_seed():
    """auprc_mean.tex: mean AUPRC of every method. Also checks and prints what the text says about the per-seed
    comparison: the W/T/L counts and best baselines of baseline_table.txt against the per-seed file, and that ARNI's
    greedy variant is never above its full variant."""
    per, means = _per_seed()
    best = {}
    for l in lines("baseline_table.txt"):
        sn = split_name(l, OLD)
        m = sn and re.match(r"\s+3\s+.*?\s(\d+/\d+/\d+)\s+(\S+)\s*$", sn[1])
        if m:
            best[OLD[sn[0]]] = (m.group(1), m.group(2).split(","))
    assert len(best) == 12
    margins = []; tot = [0, 0, 0]; greedy_better = 0
    for n in ORDER:
        wtl, names = best[n]; cnt = [0, 0, 0]
        for (seed, pick, d), b in zip(per[n], names):
            val = lambda k: float(d[k][0]) if d.get(k) else -1.0
            arni = max(val("ARNI full"), val("ARNI greedy")); greedy_better += val("ARNI greedy") > val("ARNI full")
            bv = arni if b == "ARNI" else val(b)
            top = max([arni] + [val(k) for k in FILE_COLS[1:] if not k.startswith("ARNI")])
            assert abs(bv - top) < 1e-9, (n, seed, b, bv, top)          # the named baseline is the best one on this seed
            o = float(d["ours"][0]); cnt[0] += o - bv > 2e-3; cnt[2] += bv - o > 2e-3
            margins.append(("%.3f" % bv, "%.3f" % o))
        w = [int(x) for x in wtl.split("/")]
        # the counts come from baseline_table.py (unrounded scores, tie = within 0.001); the rounded per-seed values
        # can only confirm the clear wins and losses
        assert sum(w) == 3 and cnt[0] <= w[0] and cnt[2] <= w[2], (n, cnt, wtl)
        tot = [a + b for a, b in zip(tot, w)]
    assert greedy_better == 0                                           # ARNI's column is its full variant on every seed
    total = next(re.search(r"W/T/L (\d+/\d+/\d+)", l).group(1) for l in lines("baseline_table.txt") if l.startswith("synthetic total"))
    assert "%d/%d/%d" % tuple(tot) == total, (tot, total)
    print("  W/T/L over the 36 seeds: %s; ARNI greedy is never above ARNI full" % total)
    g = [float(d["ARNI greedy"][0]) for n in KURAMOTO for _, _, d in per[n]]
    print("  ARNI greedy AUROC on the 15 Kuramoto seeds: %.3f to %.3f" % (min(g), max(g)))
    names = [b for n in ORDER for b in best[n][1]]
    print("  best baseline per seed: " + ", ".join("%s %d" % (k, names.count(k)) for k in sorted(set(names), key=lambda k: -names.count(k))))
    print("  largest loss of HetNDL on a seed: %.3f" % max(float(b) - float(o) for b, o in margins))
    write("auprc_mean.tex", tabular("l" + "c" * len(SHOWN), HEAD, [" & ".join([NAME[n]] + [means[n][k][1] for k in SHOWN]) + r"\\" for n in ORDER]),
          "baseline_table_per_seed.txt")


def netsim():
    out = []
    for l in lines("baseline_table.txt"):
        m = re.match(r"\s+vs (\w+)\s+n (\d+)\s+([\d.]+) / ([\d.]+)\s+W/T/L (\S+)\s+Wilcoxon p AUROC (\S+)\s+AUPRC (\S+)", l)
        if m:
            b, n, a, p, wtl, pa, pp = m.groups()
            two = lambda t: t + "0" if len(t.lstrip("0.")) < 2 else t          # two significant digits ("0.3" -> "0.30")
            fmt = lambda x: sci1(float(x)) if float(x) < 1e-3 else two("%.2g" % float(x))
            out.append(" & ".join([b, a, p, wtl, fmt(pa), fmt(pp)]) + r"\\")
    ours = next(re.match(r"Netsim \(27 sims\): ours ([\d.]+) / ([\d.]+)", l) for l in lines("baseline_table.txt") if l.startswith("Netsim"))
    assert len(out) == 8, len(out)
    write("netsim.tex", tabular("lccccc", r"Method & AUROC & AUPRC & W/T/L of \method{} & $p$ (AUROC) & $p$ (AUPRC)\\",
          [r"\method{} & %s & %s & & & \\" % ours.groups(), r"\addlinespace[2pt]"] + out), "baseline_table.txt")



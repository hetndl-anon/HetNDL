def l1_combined():
    """l1_sweep.txt (Kuramoto, five values) and l1_zero.txt (MixRelax, MixOsc: the default and 0) -> l1.tex, one row per
    setting and value: the script's mean AUROC / AUPRC / node read-out, and ranges over the seeds of the validation
    error, the share of |W| outside the true edges and the recall of the 2-means cut."""
    pat = (r"\s+seed (\d) (\S+)\s+AUROC (\S+) AUPRC (\S+) node (\S+) K (\S+) \| val MSE (\S+) \(best epoch (\d+)\) \| non-edge share of "
           r"\|W\| (\S+), 2-means P (\S+) R (\S+) \| last epoch: training loss (\S+), val MSE (\S+) \| pick (\w+)")
    VAL = {"0": "0", "1e-9": r"$10^{-9}$", "1e-8": r"$10^{-8}$", "default": r"$10^{-8}$", "l1zero": "0", "1e-7": r"$10^{-7}$", "1e-6": r"$10^{-6}$"}
    groups = []
    for f, keep in (("l1_sweep.txt", ["Kuramoto-+/- p- 0.5"]), ("l1_zero.txt", ["MixRelax", "MixOsc N30"])):
        for name in keep:
            runs = {}; means = {}
            for l in lines(f):
                sn = split_name(l.strip(), L1NAME)
                if not sn or sn[0] != name:
                    continue
                m = re.match(pat, sn[1]); mu = re.match(r"\s+MEAN (\S+)\s+AUROC (\S+) AUPRC (\S+) node (\S+)", sn[1])
                if m:
                    runs.setdefault(m.group(2), []).append(m.groups())
                elif mu:
                    means[mu.group(1)] = mu.groups()[1:]
            out = []
            order = ["0", "1e-9", "1e-8", "1e-7", "1e-6"] if f == "l1_sweep.txt" else ["l1zero", "default"]
            for v in order:
                r = runs[v]; assert len(r) == 3 and v in means, (name, v)
                out.append(" & ".join([VAL[v]] + ["%.3f" % float(x) for x in means[v]] + [rng([float(x[6]) for x in r], sci1),
                                      rng([float(x[8]) for x in r], "%.2f"), rng([float(x[10]) for x in r], "%.2f")]) + r"\\")
            groups.append("\n".join([r"\multicolumn{7}{@{}l}{\emph{%s}}\\" % L1NAME[name]] + out))
    write("l1.tex", tabular("ccccccc", r"$\lambda_1$ & AUROC & AUPRC & Node read-out & Validation error & $|W|$ off the edges & Recall\\",
          ["\n\\addlinespace[2pt]\n".join(groups)]), "l1_sweep.txt, l1_zero.txt")



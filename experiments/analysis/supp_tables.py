SYM = {"x": "x", "u": "u", "v": "v", "omega": r"\nu", "x_i": "x_i", "x_j": "x_j", "theta_i": r"\theta_i", "theta_j": r"\theta_j"}
FUNC = {"tanh": r"\tanh", "sin": r"\sin"}; POW = {"square": 2, "cube": 3}


def _num(v):
    s = "%.3g" % abs(v)
    if "e" in s:
        m, e = s.split("e"); s = r"%s\times10^{%d}" % (m, int(e))
    return s


def _render(node):
    """AST of a distilled expression -> (negative, tex, python, precedence, is_number). precedence: 0 sum, 1 product,
    2 atom. The python string follows the same bracketing as the tex string and is used to check it numerically."""
    full = lambda r: (("-" + (r[1] if r[3] >= 1 else "(%s)" % r[1])) if r[0] else r[1], ("-(%s)" % r[2]) if r[0] else "(%s)" % r[2])
    if isinstance(node, ast.Constant):
        return node.value < 0, _num(node.value), repr(abs(node.value)), 2, True
    if isinstance(node, ast.Name):
        return False, SYM[node.id], node.id, 2, False
    if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
        n, t, p, pr, isn = _render(node.operand)
        return (not n, t, p, pr, isn) if pr >= 1 else (True, "(%s)" % t, "(%s)" % p, 2, False)
    if isinstance(node, ast.BinOp) and isinstance(node.op, (ast.Add, ast.Sub)):
        a = _render(node.left); b = _render(node.right); nb = b[0] != isinstance(node.op, ast.Sub)
        lt, lp = full(a)
        rt = b[1] if (b[3] >= 1 or not nb) else "(%s)" % b[1]
        return False, "%s %s %s" % (lt, "-" if nb else "+", rt), "%s %s (%s)" % (lp, "-" if nb else "+", b[2]), 0, False
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Mult):
        a = _render(node.left); b = _render(node.right)
        if b[4] and not a[4]:
            a, b = b, a                                                 # a numerical factor goes first
        wrap = lambda r: r[1] if r[3] >= 1 else "(%s)" % r[1]
        sep = r"\times " if (a[4] and b[4]) else r"\," if not a[4] else ""
        return a[0] != b[0], wrap(a) + sep + wrap(b), "(%s) * (%s)" % (a[2], b[2]), 1, False
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Pow) and isinstance(node.right, ast.Constant):   # sympy's x**n
        r = _render(node.left); t, p = full(r); e = int(node.right.value); assert e == node.right.value, ast.dump(node)
        simple = (not r[0]) and r[3] == 2 and not r[4] and re.fullmatch(r"\\?[a-z]+(_[ij])?", r[1])
        return False, ("%s^{%d}" if simple else "(%s)^{%d}") % (t, e), "(%s) ** %d" % (p, e), 2, False
    if isinstance(node, ast.Call) and node.func.id in POW:
        r = _render(node.args[0]); t, p = full(r)
        simple = (not r[0]) and r[3] == 2 and not r[4] and re.fullmatch(r"\\?[a-z]+(_[ij])?", r[1])
        return False, ("%s^{%d}" if simple else "(%s)^{%d}") % (t, POW[node.func.id]), "(%s) ** %d" % (p, POW[node.func.id]), 2, False
    if isinstance(node, ast.Call) and node.func.id in FUNC:
        t, p = full(_render(node.args[0]))
        return False, "%s(%s)" % (FUNC[node.func.id], t), "math.%s(%s)" % (node.func.id, p), 2, False
    raise ValueError(ast.dump(node))


def eq_tex(s):
    """A distilled equation as printed by PySR -> inline math with constants rounded to three significant digits. The
    bracketing is checked: the python form built alongside must equal the original expression at random points."""
    tree = ast.parse(s.replace("^", "**"), mode="eval").body
    r = _render(tree); tex = ("-" + (r[1] if r[3] >= 1 else "(%s)" % r[1])) if r[0] else r[1]
    py = ("-(%s)" % r[2]) if r[0] else r[2]
    env = {"math": math, "square": lambda a: a * a, "cube": lambda a: a ** 3, "tanh": math.tanh, "sin": math.sin}
    rnd = random.Random(0)
    for _ in range(20):
        pt = {k: rnd.uniform(-2, 2) for k in SYM}
        a = eval(compile(ast.Expression(tree), "<eq>", "eval"), dict(env), dict(pt)); b = eval(py, dict(env), dict(pt))
        assert abs(a - b) <= 1e-9 * max(1.0, abs(a)), (s, py, a, b)
    return "$%s$" % tex



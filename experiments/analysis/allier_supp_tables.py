"""Supplement tables of the Allier et al. 2026 baseline (Sect. S14), generated from the scoring outputs; do not type the
numbers by hand.
  results/supplement/allier_control.txt (allier_control_table.py) -> results/supp_tables/allier_control.tex
  results/supplement/allier_rerun.txt   (allier_table.py --model PDE_N5_supp8_fig2lr_ep20) -> results/supp_tables/allier_main.tex
Run from the project root: python experiments/analysis/allier_supp_tables.py"""
import os, re

REV = "results/supplement"
OUT = "results/supp_tables"
HEAD = "%% Generated by experiments/analysis/allier_supp_tables.py from %s. Do not edit by hand.\n"


def control():
    rows = {}
    for line in open(os.path.join(REV, "allier_control.txt"), encoding="utf-8"):
        m = re.match(r"(\S+)( T(\d+))?\s+(\d) \| ([0-9.]+) / ([0-9.]+)\s+([0-9.-]+)\s+([0-9.-]+)\s+([0-9.-]+)\s+(\d+) \|", line)
        if m:
            key = (m.group(1), int(m.group(3) or 500))
            rows.setdefault(key, {})[int(m.group(4))] = dict(au=m.group(5), sg=m.group(7), r=m.group(8), ari=m.group(9))
    spec = [(("supp8_ep10", 500), "C0", "their sparse setting, 10 epochs"),
            (("supp8_fig2lr_ep10", 500), "C1", "C0 with the learning rates of their main experiment"),
            (("supp8_fig2lr_ep20", 500), "C2", "C1 with 20 epochs (used on the benchmarks)"),
            (("fig2_ep10", 500), "C3", "training of their main experiment, 10 epochs"),
            (("supp8_fig2lr_ep10", 2000), "C1", "on longer runs")]
    neg = lambda x: x.replace("-", "$-$", 1) if x.startswith("-") else x
    f = lambda d, k: "%s / %s" % (neg(d[1][k]), neg(d[2][k]))
    lines = [HEAD % "allier_control.txt", "\\begin{tabular}{@{}l>{\\raggedright\\arraybackslash}p{2.9cm}rcccc@{}}", "\\toprule",
             "& Training settings & Steps & AUROC & Sign & $r(W)$ & Type ARI\\\\", "\\midrule"]
    for key, tag, desc in spec:
        d = rows[key]
        if key[1] == 2000:
            lines.append("\\midrule")
        lines.append("%s & %s & %d & %s & %s & %s & %s\\\\" % (tag, desc, key[1], f(d, "au"), f(d, "sg"), f(d, "r"), f(d, "ari")))
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    open(os.path.join(OUT, "allier_control.tex"), "w", encoding="utf-8").write("\n".join(lines))


NAMES = {"Kuramoto σ/K 0.15": "Kuramoto-$\\omega$, $\\sigma/\\kappa$ 0.15", "Kuramoto σ/K 1.0": "Kuramoto-$\\omega$, $\\sigma/\\kappa$ 1.0",
         "Kuramoto p⁻ 0.2": "Kuramoto-$\\pm$, $p^-$ 0.2", "Kuramoto p⁻ 0.5": "Kuramoto-$\\pm$, $p^-$ 0.5",
         "BA Kuramoto p⁻ 0.5": "Kuramoto-$\\pm$ (BA)", "MixRelax (ER)": "MixRelax", "MixRelax (BA)": "MixRelax (BA)", "GLV-±": "GLV-$\\pm$"}
ORDER = ["Kuramoto σ/K 0.15", "Kuramoto σ/K 1.0", "Kuramoto p⁻ 0.2", "Kuramoto p⁻ 0.5", "BA Kuramoto p⁻ 0.5", "MixRelax (ER)",
         "MixRelax (BA)", "GLV-±"]


def main_table():
    rows, net = {}, None
    for line in open(os.path.join(REV, "allier_rerun.txt"), encoding="utf-8"):
        m = re.match(r"(.+?)\s{2,}([0-9.]+ / [0-9.]+)\s+([0-9.]+ / [0-9.]+)\s+(\d+/\d+/\d+)\s+(—|[0-9.]+ / [0-9.]+)\s+(—|[0-9.]+ / [0-9.]+)", line)
        if m and m.group(1).strip() in NAMES:
            rows[m.group(1).strip()] = m.groups()[1:]
        n = re.match(r"NetSim \((\d+) of (\d+).*HetNDL ([0-9.]+ / [0-9.]+), Allier 2026 ([0-9.]+ / [0-9.]+); W/T/L (\d+/\d+/\d+)", line)
        if n:
            net = n.groups()
    assert sorted(rows) == sorted(NAMES) and net, (sorted(rows), net)
    lines = [HEAD % "allier_rerun.txt", "\\begin{tabular}{@{}lccccc@{}}", "\\toprule",
             "Setting & \\method{} & Allier et al. & W/T/L & Sign (H / A) & Type ARI (H / A)\\\\", "\\midrule"]
    for k in ORDER:
        o, a, w, s, t = rows[k]
        lines.append("%s & %s & %s & %s & %s & %s\\\\" % (NAMES[k], o, a, w, s.replace("—", "n/a"), t.replace("—", "n/a")))
    lines += ["\\midrule", "NetSim & %s & %s & %s & n/a & n/a\\\\" % (net[2], net[3], net[4]), "\\bottomrule", "\\end{tabular}", ""]
    open(os.path.join(OUT, "allier_main.tex"), "w", encoding="utf-8").write("\n".join(lines))


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True); control(); main_table(); print("wrote allier_control.tex, allier_main.tex")
